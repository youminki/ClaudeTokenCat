/// 메뉴바 러너. 그림은 코드로 그린 픽셀맵이고 색은 SpriteTheme을 따른다.
enum Runner: String, CaseIterable {
    case cat, dog, rabbit, fox, penguin, duck, dino, hedgehog

    var displayName: String {
        switch self {
        case .cat: return "고양이"
        case .dog: return "강아지"
        case .rabbit: return "토끼"
        case .fox: return "여우"
        case .penguin: return "펭귄"
        case .duck: return "오리"
        case .dino: return "공룡"
        case .hedgehog: return "고슴도치"
        }
    }

    var art: RunnerArt {
        switch self {
        case .cat: return .cat
        case .dog: return .dog
        case .rabbit: return .rabbit
        case .fox: return .fox
        case .penguin: return .penguin
        case .duck: return .duck
        case .dino: return .dino
        case .hedgehog: return .hedgehog
        }
    }
}

